def el_fa(el):
    """'Cu_pct' -> 'مس'; an unknown column name is returned as it is."""
    return ELEMENT_FA.get(element_symbol(el), str(el))


def pct(v, d=1):
    return fa_num(v, d, suffix="٪") if v is not None else "—"


def num(v, d=None):
    return fa_num(v, d)


def p_text(p):
    """p-value for prose: very small values are not printed as zero."""
    if p is None:
        return "—"
    if p < 0.0001:
        return "کمتر از " + fa_num(0.0001, 4)
    return fa_num(p, 4)


def _list(items):
    items = [str(x) for x in items if str(x)]
    if not items:
        return "—"
    if len(items) == 1:
        return items[0]
    return "، ".join(items[:-1]) + " و " + items[-1]


def _sign_word(v):
    return "بیشتر" if (v or 0) > 0 else "کمتر"


def _precious(el):
    return element_family(el) == "precious"


